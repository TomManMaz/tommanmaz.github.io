#!/usr/bin/env python3
"""Build data/qap_instances.json and data/qap_instances.js from the QAP ledger.

Inputs (all in this repository):
  data/qap_ledger.json                 hand-maintained source of truth
  downloads/qap/instances/<name>.dat   official QAPLIB data, unmodified
  downloads/qap/solutions/<name>.sln   one verified permutation per instance

Every best known value is re-checked: the build fails unless the stored
permutation is a permutation of 1..n whose cost on the instance data equals
the ledger's bks. Run it after every change to the ledger or the files:

    python scripts/build_qap_data.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "data" / "qap_ledger.json"
INSTANCE_DIR = ROOT / "downloads" / "qap" / "instances"
SOLUTION_DIR = ROOT / "downloads" / "qap" / "solutions"
OUTPUT_JSON = ROOT / "data" / "qap_instances.json"
OUTPUT_JS = ROOT / "data" / "qap_instances.js"


class BuildError(Exception):
    pass


def integers(path):
    return [int(token) for token in re.findall(r"-?\d+", path.read_text(encoding="latin-1"))]


def read_instance(name):
    numbers = integers(INSTANCE_DIR / f"{name}.dat")
    n = numbers[0]
    if len(numbers) != 1 + 2 * n * n:
        raise BuildError(f"{name}.dat: expected {1 + 2 * n * n} numbers, found {len(numbers)}")
    return n, numbers[1:1 + n * n], numbers[1 + n * n:]


def read_solution(name, n):
    numbers = integers(SOLUTION_DIR / f"{name}.sln")
    size, value, permutation = numbers[0], numbers[1], numbers[2:]
    if size != n or sorted(permutation) != list(range(1, n + 1)):
        raise BuildError(f"{name}.sln: not a permutation of 1..{n}")
    return value, permutation


def cost(n, a, b, permutation):
    p = [location - 1 for location in permutation]
    return sum(a[i * n + j] * b[p[i] * n + p[j]] for i in range(n) for j in range(n))


def family_of(name):
    return re.match(r"[a-z]+", name).group()


def changes_since_qaplib(entry):
    official = entry.get("qaplib_2012")
    if official is None:
        return ["added"]  # in the official data archive, but not in its table
    changes = []
    if entry["bks"] != official["value"]:
        changes.append("new best known value")
    if entry["status"] == "optimal" and official["status"] == "open":
        changes.append("proved optimal")
    return changes


def gap_percent(bks, lower_bound):
    if bks == lower_bound:
        return 0.0  # also covers esc16f, whose optimum is 0
    return round(100 * (bks - lower_bound) / bks, 2)


def published_entry(entry, references):
    name, bks = entry["name"], entry["bks"]
    n, a, b = read_instance(name)
    if n != entry["n"]:
        raise BuildError(f"{name}: ledger says n={entry['n']}, data file has n={n}")
    header_value, permutation = read_solution(name, n)
    if cost(n, a, b, permutation) != bks or header_value != bks:
        raise BuildError(f"{name}: stored permutation does not cost {bks}")

    lower_bound = bks if entry["status"] == "optimal" else entry["lower_bound"]
    if lower_bound > bks:
        raise BuildError(f"{name}: lower bound {lower_bound} exceeds bks {bks}")
    for key in [entry.get("proof"), entry.get("lower_bound_source"), entry.get("bks_source"),
                *entry.get("notes", []), *(h["source"] for h in entry.get("history", []))]:
        if key is not None and key not in references:
            raise BuildError(f"{name}: unknown reference {key!r}")

    return {
        **entry,
        "family": family_of(name),
        "lower_bound": lower_bound,
        "gap_pct": gap_percent(bks, lower_bound),
        "changes": changes_since_qaplib(entry),
        "instance_url": f"downloads/qap/instances/{name}.dat",
        "solution_url": f"downloads/qap/solutions/{name}.sln",
    }


def check_files_match(names):
    for folder, suffix in [(INSTANCE_DIR, ".dat"), (SOLUTION_DIR, ".sln")]:
        on_disk = {path.stem for path in folder.glob(f"*{suffix}")}
        if on_disk != names:
            raise BuildError(f"{folder.name}: files and ledger differ: {sorted(on_disk ^ names)}")


def natural_key(entry):
    return (entry["family"], entry["n"], entry["name"])


def build():
    ledger = json.loads(LEDGER.read_text(encoding="utf-8"))
    check_files_match({entry["name"] for entry in ledger["instances"]})
    instances = sorted((published_entry(e, ledger["references"]) for e in ledger["instances"]), key=natural_key)
    data = {key: ledger[key] for key in ("updated", "objective", "references", "families")}
    data["instances"] = instances

    text = json.dumps(data, ensure_ascii=False, indent=1)
    OUTPUT_JSON.write_text(text + "\n", encoding="utf-8", newline="\n")
    OUTPUT_JS.write_text("// Generated by scripts/build_qap_data.py from data/qap_ledger.json; do not edit.\n"
                         f"window.QAP_DATA = {text};\n", encoding="utf-8", newline="\n")
    open_count = sum(entry["status"] == "open" for entry in instances)
    print(f"{len(instances)} instances verified: {len(instances) - open_count} optimal, {open_count} open")


if __name__ == "__main__":
    try:
        build()
    except BuildError as error:
        sys.exit(f"build_qap_data: {error}")
